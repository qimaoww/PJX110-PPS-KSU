# All DTBO writers share one directory lock.  The directory creation is the
# atomic operation; the PID file is only used to distinguish a live owner from
# a lock left behind by a killed shell.  Callers must install their EXIT/TERM
# trap immediately after this returns successfully.
acquire_dtbo_lock() (
  lock_dir="$1"
  [ -n "$lock_dir" ] || return 1
  if mkdir "$lock_dir" 2>/dev/null; then
    printf '%s\n' "$$" > "$lock_dir/pid" 2>/dev/null || {
      rm -rf "$lock_dir" 2>/dev/null
      return 1
    }
    return 0
  fi
  old_pid="$(cat "$lock_dir/pid" 2>/dev/null)"
  case "$old_pid" in
    ''|*[!0-9]*)
      # The winning process may be between mkdir and writing its PID. Give it
      # one short grace period before treating a metadata-less lock as stale.
      sleep 1
      old_pid="$(cat "$lock_dir/pid" 2>/dev/null)"
      case "$old_pid" in ''|*[!0-9]*) old_pid="" ;; esac
      ;;
  esac
  if [ -n "$old_pid" ] && kill -0 "$old_pid" 2>/dev/null; then
    return 1
  fi
  # Serialize stale-lock reclamation. Only one contender may remove the old
  # directory, so another process cannot simultaneously replace our new lock.
  mkdir "$lock_dir/.reclaim" 2>/dev/null || return 1
  check_pid="$(cat "$lock_dir/pid" 2>/dev/null)"
  case "$check_pid" in ''|*[!0-9]*) check_pid="" ;; esac
  if [ -n "$check_pid" ] && kill -0 "$check_pid" 2>/dev/null; then
    rmdir "$lock_dir/.reclaim" 2>/dev/null
    return 1
  fi
  rm -rf "$lock_dir" 2>/dev/null || return 1
  mkdir "$lock_dir" 2>/dev/null || return 1
  printf '%s\n' "$$" > "$lock_dir/pid" 2>/dev/null || {
    rm -rf "$lock_dir" 2>/dev/null
    return 1
  }
)

release_dtbo_lock() (
  lock_dir="$1"
  [ -n "$lock_dir" ] || return 0
  owner="$(cat "$lock_dir/pid" 2>/dev/null)"
  [ "$owner" = "$$" ] && rm -rf "$lock_dir" 2>/dev/null
  return 0
)

hash_file() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{print $1}'
  else
    busybox sha256sum "$1" | awk '{print $1}'
  fi
}

is_sha256() {
  case "$1" in
    *[!0-9a-f]*|'') return 1 ;;
  esac
  [ "$(printf '%s' "$1" | wc -c | tr -d ' ')" -eq 64 ]
}

dynamic_slot_key() (
  case "$1" in
    _a) echo "a" ;;
    _b) echo "b" ;;
    *) return 1 ;;
