backup_stock() (
  block="$1"; slot="$2"; expected="$3"
  tmp="/data/local/tmp/PJX110_PPS_KSU_backup_$$.img"
  dump_block "$block" "$tmp" || return 1
  h="$(hash_file "$tmp")"
  if [ "$h" != "$expected" ]; then
    echo "[!] Refusing backup: slot $(slot_label "$slot") is not expected stock."
    rm -f "$tmp"; return 1
  fi
  dtbo_avb_footer_valid "$tmp" || {
    echo "[!] Refusing backup: stock DTBO AVB/footer validation failed."
    rm -f "$tmp"; return 1
  }
  cp -f "$tmp" "$BACKUP_DIR/dtbo${slot}_stock.img" || { rm -f "$tmp"; return 1; }
  chmod 0600 "$BACKUP_DIR/dtbo${slot}_stock.img" 2>/dev/null
  if [ -d /sdcard ] || [ -e /sdcard ]; then
    mkdir -p /sdcard/Ace3Pro_PPS_Backup 2>/dev/null
    cp -f "$tmp" "/sdcard/Ace3Pro_PPS_Backup/dtbo${slot}_stock.img" 2>/dev/null || true
  fi
  rm -f "$tmp"
)

file_size_bytes() (
  wc -c < "$1" 2>/dev/null | tr -d ' '
)

block_size_bytes() (
  block="$1"
  if command -v blockdev >/dev/null 2>&1; then
    size="$(blockdev --getsize64 "$block" 2>/dev/null)"
    case "$size" in ''|*[!0-9]*) ;; *) [ "$size" -gt 0 ] && { echo "$size"; return 0; } ;; esac
  fi
  resolved="$(readlink -f "$block" 2>/dev/null)" || return 1
  name="${resolved##*/}"
  sectors="$(cat "/sys/class/block/$name/size" 2>/dev/null)"
  case "$sectors" in ''|*[!0-9]*) return 1 ;; esac
  [ "$sectors" -gt 0 ] && [ "$sectors" -le 2147483647 ] || return 1
  echo "$((sectors * 512))"
)

# Validate a same-filesystem temporary copy before replacing a registered file.
atomic_dtbo_copy() (
  source="$1"; destination="$2"; expected="$3"
  case "$destination" in
    "$DYNAMIC_DIR"/slot_a/stock.img|"$DYNAMIC_DIR"/slot_a/pps33.img|"$DYNAMIC_DIR"/slot_a/pps55.img|\
    "$DYNAMIC_DIR"/slot_b/stock.img|"$DYNAMIC_DIR"/slot_b/pps33.img|"$DYNAMIC_DIR"/slot_b/pps55.img) ;;
    *) return 1 ;;
  esac
  [ ! -b "$destination" ] && [ ! -L "$destination" ] || return 1
  is_sha256 "$expected" || return 1
  [ -f "$source" ] && [ "$(hash_file "$source")" = "$expected" ] || return 1
  dtbo_avb_footer_valid "$source" || return 1
  temporary="${destination}.tmp.$$"
  [ ! -e "$temporary" ] && [ ! -L "$temporary" ] || return 1
  cp -f "$source" "$temporary" || return 1
  chmod 0600 "$temporary" 2>/dev/null
  [ "$(hash_file "$temporary")" = "$expected" ] && dtbo_avb_footer_valid "$temporary" || {
    rm -f "$temporary"; return 1
  }
  sync || return 1
  mv -f "$temporary" "$destination" || return 1
  sync || return 1
  return 0
)

# Hard safety gate: every DTBO image written by this project must retain an
# AVB footer.  The Go patcher performs the full AVB/VBMeta structural check
# when its integrity is available; this raw footer check remains available for
# emergency stock restoration even if the optional patcher binary is damaged.
dtbo_avb_footer_valid() (
  image="$1"
  [ -f "$image" ] || return 1
  size="$(file_size_bytes "$image")"
  case "$size" in ''|*[!0-9]*) return 1 ;; esac
  [ "$size" -ge 64 ] || return 1
  magic="$(tail -c 64 "$image" 2>/dev/null | od -An -tx1 -N4 2>/dev/null | tr -d ' \r\n' | tr '[:upper:]' '[:lower:]')"
  [ "$magic" = "41564266" ] || return 1
  patcher="${MODDIR:-}/bin/dtbo-profile-patcher"
  if [ -x "$patcher" ] && runtime_patch_assets_compatible; then
    "$patcher" verify "$image" >/dev/null 2>&1 || return 1
  fi
  return 0
)

verify_dtbo_profile() (
  image="$1"; profile="$2"
  case "$profile" in stock|pps33|pps55) ;; *) return 1 ;; esac
  runtime_patch_assets_compatible || return 1
  output="$("$MODDIR/bin/dtbo-profile-patcher" verify "$image" 2>/dev/null)" || return 1
  printf '%s\n' "$output" | grep -Fqx 'state=ok' || return 1
  printf '%s\n' "$output" | grep -Fqx "profile=$profile"
)

