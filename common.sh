dynamic_slot_dir() (
  key="$(dynamic_slot_key "$1")" || return 1
  echo "$DYNAMIC_DIR/slot_$key"
)

dynamic_manifest_for_slot() (
  dir="$(dynamic_slot_dir "$1")" || return 1
  echo "$dir/manifest"
)

manifest_value() (
  file="$1"; key="$2"
  [ -r "$file" ] || return 1
  awk -F= -v k="$key" '$1 == k { print substr($0, index($0, "=") + 1); exit }' "$file" 2>/dev/null
)

dynamic_manifest_shape_valid() (
  file="$1"
  [ -r "$file" ] || return 1
  awk -F= '
    NF != 2 { bad = 1; exit }
    $1 !~ /^(mode|slot_suffix|stock_sha|pps33_sha|pps55_sha)$/ { bad = 1; exit }
    seen[$1]++ { bad = 1; exit }
    END {
      if (bad || seen["mode"] != 1 || seen["slot_suffix"] != 1 ||
          seen["stock_sha"] != 1 || seen["pps33_sha"] != 1 ||
          seen["pps55_sha"] != 1) exit 1
    }
  ' "$file" >/dev/null 2>&1
)

dynamic_manifest_valid() (
  slot="$1"
  manifest="$(dynamic_manifest_for_slot "$slot")" || return 1
  [ -r "$manifest" ] || return 1
  dynamic_manifest_shape_valid "$manifest" || return 1
  [ "$(manifest_value "$manifest" slot_suffix)" = "$slot" ] || return 1
  mode="$(manifest_value "$manifest" mode)"
  case "$mode" in patch|full) ;; *) return 1 ;; esac
  stock_sha="$(manifest_value "$manifest" stock_sha)"
  pps33_sha="$(manifest_value "$manifest" pps33_sha)"
  pps55_sha="$(manifest_value "$manifest" pps55_sha)"
  is_sha256 "$stock_sha" || return 1
  [ -z "$pps33_sha" ] || is_sha256 "$pps33_sha" || return 1
  [ -z "$pps55_sha" ] || is_sha256 "$pps55_sha" || return 1
  dynamic_endpoint_hashes_distinct "$stock_sha" "$pps33_sha" "$pps55_sha" || return 1
  if [ "$mode" = "full" ]; then
    is_sha256 "$pps33_sha" && is_sha256 "$pps55_sha" || return 1
  fi
)

dynamic_endpoint_hashes_distinct() (
  stock="$1"; p33="$2"; p55="$3"
  [ -z "$p33" ] || [ "$p33" != "$stock" ] || return 1
  [ -z "$p55" ] || [ "$p55" != "$stock" ] || return 1
  [ -z "$p33" ] || [ -z "$p55" ] || [ "$p33" != "$p55" ] || return 1
)

dynamic_mode_for_slot() (
  slot="$1"
  dynamic_manifest_valid "$slot" || return 1
  manifest="$(dynamic_manifest_for_slot "$slot")"
  manifest_value "$manifest" mode
)

dynamic_sha_for_profile() (
  slot="$1"; profile="$2"
  dynamic_manifest_valid "$slot" || return 1
  manifest="$(dynamic_manifest_for_slot "$slot")"
  case "$profile" in
    stock) manifest_value "$manifest" stock_sha ;;
    pps33) manifest_value "$manifest" pps33_sha ;;
    pps55) manifest_value "$manifest" pps55_sha ;;
    *) return 1 ;;
  esac
)

dynamic_profile_for_hash() (
  slot="$1"; hash="$2"
  dynamic_manifest_valid "$slot" || { echo unknown; return 1; }
  for profile in stock pps33 pps55; do
    expected="$(dynamic_sha_for_profile "$slot" "$profile")"
    [ -n "$expected" ] || continue
    if [ "$hash" = "$expected" ]; then
      echo "$profile"
      return 0
    fi
  done
  echo unknown
  return 1
)

dynamic_image_for_profile() (
  slot="$1"; profile="$2"
  dir="$(dynamic_slot_dir "$slot")" || return 1
  case "$profile" in
    stock|pps33|pps55) echo "$dir/$profile.img" ;;
    *) return 1 ;;
  esac
)

write_dynamic_manifest() (
  slot="$1"; mode="$2"; stock_sha="$3"; pps33_sha="$4"; pps55_sha="$5"
  case "$slot" in _a|_b) ;; *) return 1 ;; esac
  case "$mode" in patch|full) ;; *) return 1 ;; esac
  is_sha256 "$stock_sha" || return 1
  [ -z "$pps33_sha" ] || is_sha256 "$pps33_sha" || return 1
  [ -z "$pps55_sha" ] || is_sha256 "$pps55_sha" || return 1
  dynamic_endpoint_hashes_distinct "$stock_sha" "$pps33_sha" "$pps55_sha" || return 1
  if [ "$mode" = "full" ]; then
    is_sha256 "$pps33_sha" && is_sha256 "$pps55_sha" || return 1
  fi
  dir="$(dynamic_slot_dir "$slot")" || return 1
  mkdir -p "$dir" || return 1
  manifest="$dir/manifest"
  # Full -> Patch stays forbidden within the same DTBO generation. Only a
  # separately validated OTA stock generation may be registered manually.
  if [ "$mode" = "patch" ] && [ -r "$manifest" ] && grep -Fqx 'mode=full' "$manifest"; then
    ota_patch_transition_allowed "$slot" "$stock_sha" || return 1
  fi
  tmp="$dir/.manifest.$$"
  {
    printf 'mode=%s\n' "$mode"
    printf 'slot_suffix=%s\n' "$slot"
    printf 'stock_sha=%s\n' "$stock_sha"
    printf 'pps33_sha=%s\n' "$pps33_sha"
    printf 'pps55_sha=%s\n' "$pps55_sha"
  } > "$tmp" || { rm -f "$tmp"; return 1; }
  chmod 0600 "$tmp" 2>/dev/null
  mv -f "$tmp" "$manifest"
)

# Validate the persistent image set before advertising a dynamic mode.  Patch
# mode only requires its exact stock backup; full mode requires all three
# endpoints.  The write scripts perform the stronger DTBO structure check
# immediately before a write.
dynamic_stock_asset_valid() (
  dynamic_stock_image_for_recovery "$1" >/dev/null
)

# Return only a stock image pinned by this slot's valid dynamic manifest. An
# independent, previously registered generation can rescue a damaged primary
# backup; never choose a different generation merely because it is available.
dynamic_stock_image_for_recovery() (
  slot="$1"
  dynamic_manifest_valid "$slot" || return 1
  expected="$(dynamic_sha_for_profile "$slot" stock)" || return 1
  image="$(dynamic_image_for_profile "$slot" stock)" || return 1
  if [ -f "$image" ] && [ "$(hash_file "$image" 2>/dev/null)" = "$expected" ] && dtbo_avb_footer_valid "$image"; then
    echo "$image"; return 0
  fi
  generation="$(rescue_slot_dir "$slot")/$expected"
  manifest="$generation/manifest"
  rescue_manifest_shape_valid "$manifest" || return 1
  [ "$(manifest_value "$manifest" format)" = "1" ] || return 1
  [ "$(manifest_value "$manifest" slot_suffix)" = "$slot" ] || return 1
  [ "$(manifest_value "$manifest" stock_sha)" = "$expected" ] || return 1
  is_sha256 "$(manifest_value "$manifest" patcher_sha)" || return 1
  image="$generation/stock.img"
  size="$(manifest_value "$manifest" stock_size)"
  case "$size" in ''|*[!0-9]*) return 1 ;; esac
  [ -f "$image" ] && [ "$(file_size_bytes "$image")" = "$size" ] || return 1
  [ "$(hash_file "$image" 2>/dev/null)" = "$expected" ] || return 1
  dtbo_avb_footer_valid "$image" || return 1
  echo "$image"
)

dynamic_assets_valid() (
  slot="$1"
  mode="$2"
  dynamic_manifest_valid "$slot" || return 1
  [ "$(dynamic_mode_for_slot "$slot")" = "$mode" ] || return 1
  # Mirror fallback is a restoration-only capability, not a PPS green light.
  image="$(dynamic_image_for_profile "$slot" stock)" || return 1
  expected="$(dynamic_sha_for_profile "$slot" stock)" || return 1
  [ -f "$image" ] && [ "$(hash_file "$image" 2>/dev/null)" = "$expected" ] || return 1
  dtbo_avb_footer_valid "$image" || return 1
  if [ "$mode" = "full" ]; then
    for profile in pps33 pps55; do
      image="$(dynamic_image_for_profile "$slot" "$profile")" || return 1
      expected="$(dynamic_sha_for_profile "$slot" "$profile")" || return 1
      [ -f "$image" ] && [ "$(hash_file "$image" 2>/dev/null)" = "$expected" ] || return 1
      dtbo_avb_footer_valid "$image" || return 1
    done
  fi
  return 0
)

