rescue_generation_valid() (
  slot="$1"; generation="$2"; expected="$3"
  case "$slot" in _a|_b) ;; *) return 1 ;; esac
  is_sha256 "$expected" || return 1
  manifest="$generation/manifest"
  image="$generation/stock.img"
  patcher="$generation/dtbo-profile-patcher"
  rescue_manifest_shape_valid "$manifest" || return 1
  [ "$(manifest_value "$manifest" format)" = "1" ] || return 1
  [ "$(manifest_value "$manifest" slot_suffix)" = "$slot" ] || return 1
  [ "$(manifest_value "$manifest" stock_sha)" = "$expected" ] || return 1
  registered_patcher_sha="$(manifest_value "$manifest" patcher_sha)"
  is_sha256 "$registered_patcher_sha" || return 1
  stock_size="$(manifest_value "$manifest" stock_size)"
  case "$stock_size" in ''|*[!0-9]*) return 1 ;; esac
  [ -f "$image" ] && [ "$(file_size_bytes "$image")" = "$stock_size" ] || return 1
  [ "$(hash_file "$image" 2>/dev/null)" = "$expected" ] || return 1
  dtbo_avb_footer_valid "$image" || return 1
  # Immutable rescue generations may retain a verified older patcher across
  # a module update. Match the generation's own pinned hash, not the new binary.
  [ -f "$patcher" ] && [ "$(hash_file "$patcher" 2>/dev/null)" = "$registered_patcher_sha" ] || return 1
)

rescue_bundle_valid() (
  slot="$1"; expected="${2:-}"
  case "$slot" in _a|_b) ;; *) return 1 ;; esac
  slot_dir="$(rescue_slot_dir "$slot")" || return 1
  [ -r "$slot_dir/active" ] || return 1
  active="$(tr -d '\r\n ' < "$slot_dir/active" 2>/dev/null)"
  is_sha256 "$active" || return 1
  [ -z "$expected" ] || [ "$active" = "$expected" ] || return 1
  rescue_generation_valid "$slot" "$slot_dir/$active" "$active" || return 1
  source_script="$MODDIR/rescue/restore_stock.sh"
  persistent_script="$RESCUE_DIR/restore_stock.sh"
  [ -f "$source_script" ] && [ -f "$persistent_script" ] || return 1
  [ "$(hash_file "$source_script" 2>/dev/null)" = "$(hash_file "$persistent_script" 2>/dev/null)" ]
)

export_rescue_bundle() (
  slot="$1"; stock_sha="$2"
  [ -d /sdcard ] || [ -e /sdcard ] || return 1
  source_root="$RESCUE_DIR"
  export_root="/sdcard/Ace3Pro_PPS_Backup/recovery"
  key="$(dynamic_slot_key "$slot")" || return 1
  source_generation="$source_root/slot_$key/$stock_sha"
  [ -d "$source_generation" ] || return 1
  mkdir -p "$export_root/slot_$key" || return 1
  target_generation="$export_root/slot_$key/$stock_sha"
  if [ ! -d "$target_generation" ]; then
    temp_generation="$export_root/slot_$key/.generation.$stock_sha.$$"
    mkdir "$temp_generation" || return 1
    cp -f "$source_generation/stock.img" "$temp_generation/stock.img" &&
      cp -f "$source_generation/dtbo-profile-patcher" "$temp_generation/dtbo-profile-patcher" &&
      cp -f "$source_generation/manifest" "$temp_generation/manifest" || return 1
    chmod 0700 "$temp_generation/dtbo-profile-patcher" 2>/dev/null
    mv "$temp_generation" "$target_generation" || return 1
  fi
  script_tmp="$export_root/.restore_stock.sh.$$"
  cp -f "$source_root/restore_stock.sh" "$script_tmp" || return 1
  chmod 0700 "$script_tmp" 2>/dev/null
  mv -f "$script_tmp" "$export_root/restore_stock.sh" || return 1
  active_tmp="$export_root/slot_$key/.active.$$"
  printf '%s\n' "$stock_sha" > "$active_tmp" || return 1
  mv -f "$active_tmp" "$export_root/slot_$key/active" || return 1
  return 0
)

# Create an immutable, per-slot recovery generation before any non-stock DTBO
# write. The generation lives outside the KernelSU module directory and is
# committed by its small active pointer only after all files pass validation.
prepare_rescue_bundle() (
  slot="$1"; stock_image="$2"; stock_sha="$3"
  case "$slot" in _a|_b) ;; *) return 1 ;; esac
  is_sha256 "$stock_sha" || return 1
  [ -f "$stock_image" ] && [ "$(hash_file "$stock_image" 2>/dev/null)" = "$stock_sha" ] || return 1
  dtbo_avb_footer_valid "$stock_image" || return 1
  runtime_patch_assets_compatible || return 1
  verify_dtbo_profile "$stock_image" stock || return 1
  source_script="$MODDIR/rescue/restore_stock.sh"
  [ -r "$source_script" ] || return 1

  mkdir -p "$RESCUE_DIR" || return 1
  script_tmp="$RESCUE_DIR/.restore_stock.sh.$$"
  cp -f "$source_script" "$script_tmp" || return 1
  chmod 0700 "$script_tmp" 2>/dev/null
  [ "$(hash_file "$script_tmp" 2>/dev/null)" = "$(hash_file "$source_script" 2>/dev/null)" ] || return 1
  mv -f "$script_tmp" "$RESCUE_DIR/restore_stock.sh" || return 1

  slot_dir="$(rescue_slot_dir "$slot")" || return 1
  mkdir -p "$slot_dir" || return 1
  generation="$slot_dir/$stock_sha"
  generation_ready=0
  if [ -d "$generation" ] && [ ! -L "$generation" ] && rescue_generation_valid "$slot" "$generation" "$stock_sha"; then
    generation_ready=1
  fi
  if [ "$generation_ready" != "1" ]; then
    if [ -e "$generation" ]; then
      [ -d "$generation" ] && [ ! -L "$generation" ] || return 1
    fi
    temp_generation="$slot_dir/.generation.$stock_sha.$$"
    mkdir "$temp_generation" || return 1
    cp -f "$stock_image" "$temp_generation/stock.img" &&
      cp -f "$MODDIR/bin/dtbo-profile-patcher" "$temp_generation/dtbo-profile-patcher" || return 1
    chmod 0600 "$temp_generation/stock.img" 2>/dev/null
    chmod 0700 "$temp_generation/dtbo-profile-patcher" 2>/dev/null
    stock_size="$(file_size_bytes "$temp_generation/stock.img")"
    {
      printf 'format=1\n'
      printf 'slot_suffix=%s\n' "$slot"
      printf 'stock_sha=%s\n' "$stock_sha"
      printf 'stock_size=%s\n' "$stock_size"
      printf 'patcher_sha=%s\n' "$PPS_PATCHER_SHA256"
    } > "$temp_generation/manifest" || return 1
    chmod 0600 "$temp_generation/manifest" 2>/dev/null
    rescue_generation_valid "$slot" "$temp_generation" "$stock_sha" || return 1
    if [ -d "$generation" ]; then
      # Repair only with this exact, freshly verified stock SHA. Commit the
      # manifest last so a power loss cannot advertise incomplete new files.
      mv -f "$temp_generation/stock.img" "$generation/stock.img" || return 1
      mv -f "$temp_generation/dtbo-profile-patcher" "$generation/dtbo-profile-patcher" || return 1
      mv -f "$temp_generation/manifest" "$generation/manifest" || return 1
      rmdir "$temp_generation" || return 1
    else
      mv "$temp_generation" "$generation" || return 1
    fi
    rescue_generation_valid "$slot" "$generation" "$stock_sha" || return 1
  fi

  active_tmp="$slot_dir/.active.$$"
  printf '%s\n' "$stock_sha" > "$active_tmp" || return 1
  chmod 0600 "$active_tmp" 2>/dev/null
  mv -f "$active_tmp" "$slot_dir/active" || return 1
  sync
  rescue_bundle_valid "$slot" "$stock_sha" || return 1
  export_rescue_bundle "$slot" "$stock_sha" 2>/dev/null || true
  return 0
)

record_rescue_write_intent() (
  slot="$1"; stock_sha="$2"; target_sha="$3"
  case "$slot" in _a|_b) ;; *) return 1 ;; esac
  is_sha256 "$stock_sha" && is_sha256 "$target_sha" || return 1
  rescue_bundle_valid "$slot" "$stock_sha" || return 1
  temp="$RESCUE_DIR/.last_write.$$"
  {
    printf 'format=1\n'
    printf 'slot_suffix=%s\n' "$slot"
    printf 'stock_sha=%s\n' "$stock_sha"
    printf 'target_sha=%s\n' "$target_sha"
  } > "$temp" || return 1
  chmod 0600 "$temp" 2>/dev/null
  mv -f "$temp" "$RESCUE_DIR/last_write" || return 1
  if [ -d /sdcard/Ace3Pro_PPS_Backup/recovery ]; then
    cp -f "$RESCUE_DIR/last_write" /sdcard/Ace3Pro_PPS_Backup/recovery/last_write 2>/dev/null || true
  fi
  sync
)

clear_rescue_write_intent() (
  slot="$1"; stock_sha="$2"
  journal="$RESCUE_DIR/last_write"
  [ -r "$journal" ] || return 0
  [ "$(manifest_value "$journal" format 2>/dev/null)" = "1" ] || return 1
  [ "$(manifest_value "$journal" slot_suffix 2>/dev/null)" = "$slot" ] || return 1
  [ "$(manifest_value "$journal" stock_sha 2>/dev/null)" = "$stock_sha" ] || return 1
  rm -f "$journal" 2>/dev/null || return 1
  rm -f /sdcard/Ace3Pro_PPS_Backup/recovery/last_write 2>/dev/null || true
  sync
)

clear_rescue_write_intent_for_verified_stock() (
