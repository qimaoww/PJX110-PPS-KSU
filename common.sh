)

rescue_last_written_slot() (
  journal="$RESCUE_DIR/last_write"
  [ -r "$journal" ] || return 1
  [ "$(manifest_value "$journal" format 2>/dev/null)" = "1" ] || return 1
  slot="$(manifest_value "$journal" slot_suffix 2>/dev/null)"
  stock_sha="$(manifest_value "$journal" stock_sha 2>/dev/null)"
  target_sha="$(manifest_value "$journal" target_sha 2>/dev/null)"
  case "$slot" in _a|_b) ;; *) return 1 ;; esac
  is_sha256 "$stock_sha" && is_sha256 "$target_sha" || return 1
  echo "$slot"
)

dtbo_block_device_valid() { [ -b "$1" ]; }

dtbo_write_target_valid() (
  block="$1"; slot="$2"
  case "$slot" in _a|_b) ;; *) return 1 ;; esac
  trusted_slot_conflict && return 1
  [ "$(trusted_slot_suffix)" = "$slot" ] || return 1
  expected_block="$(find_dtbo_block_for_slot "$slot")" || return 1
  [ -n "$block" ] && [ "$block" = "$expected_block" ] && dtbo_block_device_valid "$block"
)

write_verify() (
  image="$1"; expected="$2"; block="$3"; fallback="$4"; fallback_sha="$5"; slot="$6"; expected_current="${7:-}"
  is_sha256 "$expected" || { echo "[!] Invalid expected DTBO hash; refusing write."; return 1; }
  is_sha256 "$expected_current" || { echo "[!] Missing current DTBO hash; refusing write."; return 1; }

  source_family="$(dtbo_family_for_hash "$expected_current" 2>/dev/null)"
  # A manually registered OTA stock can also be in the static whitelist.
  # Its matching registration owns the endpoint set; never mix both sets.
  if dynamic_profile_for_hash "$slot" "$expected_current" >/dev/null; then
    target_profile="$(dynamic_profile_for_hash "$slot" "$expected")"
    case "$target_profile" in
      stock) ;;
      pps33|pps55)
        runtime_patch_assets_compatible && verify_dtbo_profile "$image" "$target_profile" || {
          echo "[!] Dynamic PPS integrity/structure is unavailable; refusing write."; return 1
        }
        ;;
      *) echo "[!] Target is not a registered dynamic endpoint; refusing write."; return 1 ;;
    esac
    required_stock_sha="$(dynamic_sha_for_profile "$slot" stock)" || return 1
  else
    [ "$source_family" != "unknown" ] && [ -n "$source_family" ] || return 1
    [ "$(dtbo_family_for_hash "$expected" 2>/dev/null)" = "$source_family" ] || {
      echo "[!] Refusing cross-firmware DTBO write."; return 1
    }
    required_stock_sha="$(stock_sha_for_family "$source_family")" || return 1
  fi
  [ "$fallback_sha" = "$required_stock_sha" ] || {
    echo "[!] Fallback is not the exact firmware stock endpoint; refusing write."; return 1
  }

  dtbo_write_target_valid "$block" "$slot" || {
    echo "[!] Refusing write: target is not the fixed DTBO block for trusted slot $slot."
    return 1
  }

  isz="$(file_size_bytes "$image")"
  bsz="$(block_size_bytes "$block")" || {
    echo "[!] Cannot determine DTBO partition size; refusing write."
    return 1
  }
  case "$bsz" in ''|*[!0-9]*) echo "[!] Invalid DTBO partition size; refusing write."; return 1 ;; esac
  if [ "$isz" != "$bsz" ]; then
    echo "[!] Image/partition size mismatch: image=$isz block=$bsz"
    echo "[!] Refusing DTBO write."
    return 1
  fi

  ih="$(hash_file "$image")"
  [ "$ih" = "$expected" ] || { echo "[!] Embedded image hash mismatch; refusing write."; return 1; }
  dtbo_avb_footer_valid "$image" || {
    echo "[!] Refusing DTBO write: AVB footer/VBMeta validation failed or was removed."
    return 1
  }
  [ -f "$fallback" ] && [ "$(file_size_bytes "$fallback")" = "$bsz" ] &&
    [ "$(hash_file "$fallback")" = "$fallback_sha" ] && dtbo_avb_footer_valid "$fallback" || {
    echo "[!] Exact stock rollback image is unavailable; refusing write."; return 1
  }
  if runtime_patch_assets_compatible; then
    verify_dtbo_profile "$fallback" stock || {
      echo "[!] Rollback image is not structurally verified stock; refusing write."; return 1
    }
  fi

  restore_fallback() {
    [ -n "$fallback" ] && [ -f "$fallback" ] || return 1
    is_sha256 "$fallback_sha" || return 1
    [ "$(file_size_bytes "$fallback")" = "$bsz" ] || return 1
    [ "$(hash_file "$fallback")" = "$fallback_sha" ] || return 1
    dtbo_avb_footer_valid "$fallback" || return 1
    echo "[!] Attempting immediate exact-family stock restore..."
    dtbo_write_target_valid "$block" "$slot" || return 1
    dd if="$fallback" of="$block" bs=4194304 2>/dev/null || return 1
    sync
    restore_hash="$(block_hash "$block")" || restore_hash=""
    if [ "$restore_hash" = "$fallback_sha" ]; then
      echo "[+] Stock DTBO restored."
      return 0
    fi
    echo "[!] WARNING: restore verification failed."
    return 1
  }

  echo "[*] Writing DTBO..."
  [ "$(block_hash "$block")" = "$expected_current" ] || {
    echo "[!] Current DTBO changed after preparation; refusing overwrite."
    return 1
  }
  dtbo_write_target_valid "$block" "$slot" || {
    echo "[!] DTBO target changed during validation; refusing write."
    return 1
  }
  if ! dd if="$image" of="$block" bs=4194304 2>/dev/null; then
    echo "[!] DTBO write command failed."
    restore_fallback || true
    return 1
  fi
  sync
  rh="$(block_hash "$block")" || rh=""
  if [ "$rh" = "$expected" ]; then
    echo "[+] DTBO readback verified: $rh"
    return 0
  fi

  echo "[!] Readback verification failed."
  restore_fallback || true
  return 1
)
