dump_block() (
  block="$1"; out="$2"
  read_slot="$(trusted_slot_suffix)" || return 1
  dtbo_write_target_valid "$block" "$read_slot" || return 1
  # A dump is an ordinary file, never another device or a special filesystem.
  case "$out" in /dev/*|/proc/*|/sys/*|'') return 1 ;; esac
  [ "$out" != "$block" ] && [ ! -L "$out" ] || return 1
  [ ! -e "$out" ] || [ -f "$out" ] || return 1
  rm -f "$out"
  dd if="$block" of="$out" bs=4194304 2>/dev/null
)

